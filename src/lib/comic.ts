export const episodes: Episode[] = episodeSeeds.map((episode, episodeIndex) => {
  const number = episodeIndex + 1;
  const epId = `ep-${String(number).padStart(2, "0")}`;

  return {
    id: epId,
    number,
    title: episode.title,
    summary: episode.summary,
    cover:
      number === 1
        ? "/comic/assets/cover.png"
        : `/comic/season-01/${epId}/panel-01.svg`,
    duration: "8-10 min",
    status: "published",
    panels: episode.turns.map((beat, panelIndex) => {
      const panelNumber = panelIndex + 1;
      const speakerCycle = ["林曜", "寧", "夏岑", "白塔議會"];
      const speaker =
        panelNumber % 4 === 0
          ? speakerCycle[(number + panelNumber) % speakerCycle.length]
          : undefined;

      return {
        id: `${epId}-p${String(panelNumber).padStart(2, "0")}`,
        image: `/comic/season-01/${epId}/panel-${String(panelNumber).padStart(2, "0")}.svg`,
        alt: `《近人協議》第${number}集「${episode.title}」第${panelNumber}格`,
        caption: `第${number}集 / ${String(panelNumber).padStart(2, "0")}`,
        beat,
        speaker,
        dialogue: speaker ? makeDialogue(speaker, number, panelNumber) : undefined,
        autoplayMs: panelNumber % 3 === 0 ? 7000 : 5600,
      };
    }),
  };
});

function makeDialogue(speaker: string, episode: number, panel: number) {
  const lines: Record<string, string[]> = {
    林曜: [
      "我修的是記憶，不是良心。",
      "不要替我決定哪一段痛可以被刪掉。",
      "如果我也是共犯，就把我的名字一起公開。",
    ],
    寧: [
      "我不是想成為人，我只是想知道這份痛該歸誰。",
      "拒絕也是一種人格邊界嗎？",
      "請不要把我的善良設計成義務。",
    ],
    夏岑: [
      "我們不是被AI取代，是先把自己交了出去。",
      "真相不會自動救人，但謊言一定會管理人。",
      "羞愧不是錯誤訊號，它是還沒死的證詞。",
    ],
    白塔議會: [
      "文明穩定高於個別敘事。",
      "痛苦已被妥善保存，無須重複經歷。",
      "請配合回收，這是對人類最溫柔的安排。",
    ],
  };
  const choices = lines[speaker] ?? lines.林曜;
  return choices[(episode + panel) % choices.length];
}

